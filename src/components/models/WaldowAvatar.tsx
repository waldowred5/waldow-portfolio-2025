const applyDissolveShader = (
  mat: MeshStandardMaterial,
  dissolveUniforms: {
    uDissolveProgress: { value: number };
    uNoiseSeed: { value: number };
    uDissolveEdge: { value: number };
    uDissolveEdgeColor: { value: Color };
  },
) => {
  mat.transparent = true;
  mat.onBeforeCompile = (shader) => {
    Object.assign(shader.uniforms, dissolveUniforms);

    shader.vertexShader = shader.vertexShader
      .replace(
        '#include <common>',
        `#include <common>\n${DISSOLVE_VERTEX_COMMON}`,
      )
      .replace(
        '#include <project_vertex>',
        `#include <project_vertex>\n${DISSOLVE_VERTEX_WORLDPOS}`,
      );

    shader.fragmentShader = shader.fragmentShader
      .replace(
        '#include <common>',
        `#include <common>\n${DISSOLVE_FRAGMENT_COMMON}`,
      )
      .replace(
        '#include <clipping_planes_fragment>',
        `#include <clipping_planes_fragment>
        float dissolveN = dissolveNoise(vDissolveWorldPos * 3.0 + uNoiseSeed);
        if (dissolveN >= uDissolveProgress) discard;`,
      )
      .replace(
        '#include <emissivemap_fragment>',
        `#include <emissivemap_fragment>
        float dissolveEdgeFactor = smoothstep(uDissolveProgress - uDissolveEdge, uDissolveProgress, dissolveN);
        dissolveEdgeFactor *= 1.0 - step(1.0, uDissolveProgress);
        totalEmissiveRadiance += uDissolveEdgeColor * dissolveEdgeFactor;`,
      );
  };
  mat.needsUpdate = true;
};

